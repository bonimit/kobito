"""Music and sound effects.

All the audio is generated by tools/make_audio.py into assets/audio:
music/<track>.ogg loops (one per world, secret stage and menu) and
sfx/<name>.ogg one-shots. This module just plays them:

    audio.music("tokyo")      # start (or keep) a looping track
    audio.play("coin")        # a sound effect
    audio.duck(True)          # quieter music under a quiz box

Every call is safe to make anywhere: with no sound device, a missing file
or the mixer failing to start, they quietly do nothing -- sound must never
be the reason the game won't run. Music and sound effects can each be
switched off in the pause menu (remembered in the save, see
kobito/save_game.py).
"""

import pygame

from kobito.assets import ASSETS_DIR

AUDIO_DIR = ASSETS_DIR / "audio"
MUSIC_VOLUME = 0.55
DUCKED_VOLUME = 0.22
SFX_VOLUME = 0.7

# Which track plays where. World themes and secret-room styles use the
# track of the same name; these cover the rest.
MENU_TRACK = "title"
STAGE_END_TRACK = "results"

_state = {"ready": None, "music": True, "sfx": True, "track": None, "ducked": False}
_sounds = {}


def _ready():
    """Starts the mixer the first time sound is needed. False if it can't."""
    if _state["ready"] is None:
        try:
            if not pygame.mixer.get_init():
                pygame.mixer.init(frequency=22050, size=-16, channels=2, buffer=512)
            pygame.mixer.set_num_channels(16)
            _state["ready"] = True
        except Exception:
            _state["ready"] = False
    return _state["ready"]


# -- Settings ---------------------------------------------------------------------

def music_enabled():
    return _state["music"]


def sfx_enabled():
    return _state["sfx"]


def set_music(on):
    _state["music"] = bool(on)
    if not on:
        stop_music(keep_track=True)
    elif _state["track"]:
        track, _state["track"] = _state["track"], None
        music(track)


def set_sfx(on):
    _state["sfx"] = bool(on)


def toggle_music():
    set_music(not _state["music"])


def toggle_sfx():
    set_sfx(not _state["sfx"])


# -- Playing ----------------------------------------------------------------------

def play(name, volume=1.0):
    if not _state["sfx"] or not _ready():
        return
    sound = _sounds.get(name)
    if sound is None:
        path = AUDIO_DIR / "sfx" / f"{name}.ogg"
        try:
            sound = pygame.mixer.Sound(str(path))
        except Exception:
            sound = False
        _sounds[name] = sound
    if sound:
        try:
            sound.set_volume(SFX_VOLUME * volume)
            sound.play()
        except Exception:
            pass


def music(track):
    """Loops `track` (keeps playing, without restarting, if it already is)."""
    if track == _state["track"] and (pygame.mixer.get_init() and pygame.mixer.music.get_busy()
                                     or not _state["music"]):
        return
    _state["track"] = track
    if not _state["music"] or not _ready():
        return
    path = AUDIO_DIR / "music" / f"{track}.ogg"
    if not path.exists():
        return
    try:
        pygame.mixer.music.load(str(path))
        pygame.mixer.music.set_volume(DUCKED_VOLUME if _state["ducked"] else MUSIC_VOLUME)
        pygame.mixer.music.play(loops=-1, fade_ms=300)
    except Exception:
        pass


def pick(track, fallback):
    """`track` if its file is there, else `fallback`."""
    return track if (AUDIO_DIR / "music" / f"{track}.ogg").exists() else fallback


def stop_music(keep_track=False):
    if not keep_track:
        _state["track"] = None
    if _state["ready"]:
        try:
            pygame.mixer.music.fadeout(250)
        except Exception:
            pass


def duck(on):
    """Turns the music down (e.g. while a quiz box is open) or back up."""
    _state["ducked"] = bool(on)
    if _state["ready"]:
        try:
            pygame.mixer.music.set_volume(DUCKED_VOLUME if on else MUSIC_VOLUME)
        except Exception:
            pass


def current_track():
    return _state["track"]
